/* ⭐ Find airport by ICAO or IATA */
export const findAirport = (code) => {
  if (!code) return null;
  const c = String(code).toUpperCase().trim();
  return AIRPORTS.find((a) => a.icao === c || a.iata === c) || null;
};

/* ⭐ Get full name for GenDec */
export const getAirportFull = (code) => {
  const a = findAirport(code);
  if (!a) return code || "—";
  return `${a.city.toUpperCase()} / ${a.country}`;
};

/* ⭐ Search airports */
export const searchAirports = (query, limit = 10) => {
  if (!query || query.length < 2) return [];
  const q = String(query).toLowerCase().trim();
  return AIRPORTS.filter(
    (a) =>
      a.icao.toLowerCase().includes(q) ||
      a.iata.toLowerCase().includes(q) ||
      a.name.toLowerCase().includes(q) ||
      a.city.toLowerCase().includes(q) ||
      a.country.toLowerCase().includes(q)
  ).slice(0, limit);
};

/* ⭐ Distance in Nautical Miles (Haversine) */
export const distanceNM = (depCode, arrCode) => {
  const d = findAirport(depCode);
  const a = findAirport(arrCode);
  if (!d || !a || d.lat == null || a.lat == null) return 0;

  const R = 3440.065;
  const toRad = (x) => (x * Math.PI) / 180;

  const dLat = toRad(a.lat - d.lat);
  const dLon = toRad(a.lon - d.lon);
  const lat1 = toRad(d.lat);
  const lat2 = toRad(a.lat);

  const h =
    Math.sin(dLat / 2) ** 2 +
    Math.cos(lat1) * Math.cos(lat2) * Math.sin(dLon / 2) ** 2;

  return Math.round(2 * R * Math.asin(Math.sqrt(h)));
};

/* ⭐ Get coordinates */
export const getAirportCoords = (code) => {
  const a = findAirport(code);
  return a && a.lat != null ? { lat: a.lat, lon: a.lon } : null;
};

